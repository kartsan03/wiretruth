"""Render the scenario catalog from suite data."""

from collections import Counter
from pathlib import Path

from wiretruth.formats import load_fixture, load_scenario
from wiretruth.lint import SetupError


def _cell(text: str) -> str:
    return text.replace("|", r"\|").replace("\r\n", "\n").replace("\r", "\n").replace("\n", "<br>")


def render(root: Path) -> str:
    directory = root / "suite" / "scenarios"
    if not directory.is_dir():
        raise SetupError(f"{directory}: no such directory")
    families = {
        folder.name: sorted(
            (load_scenario(path) for path in sorted(folder.glob("*.json"))),
            key=lambda scenario: scenario.id,
        )
        for folder in sorted(directory.iterdir())
        if folder.is_dir()
    }
    fixtures = [
        load_fixture(path) for path in sorted((root / "suite" / "fixtures").glob("*/*.json"))
    ]
    tiers = {fixture.id: fixture.tier for fixture in fixtures}
    counts = Counter(fixture.tier for fixture in fixtures)
    providers = {
        provider
        for scenarios in families.values()
        for scenario in scenarios
        for provider in scenario.providers
    }
    count = sum(len(scenarios) for scenarios in families.values())
    lines = [
        "<!-- Generated by `wiretruth catalog`. Do not edit by hand. -->",
        "",
        "# Scenario catalog",
        "",
        "A scenario is one edge case: the call to make and the requirements a library must meet.",
        "Fixture tiers: `recorded` = real provider bytes; "
        "`documented` = transcribed from official docs;",
        "`derived` = a named transform of one of those.",
        "",
        f"{count} scenarios; {len(providers)} providers; fixtures: "
        f"{counts['recorded']} recorded, {counts['documented']} documented, "
        f"{counts['derived']} derived.",
    ]
    for family, scenarios in families.items():
        lines.extend(
            [
                "",
                f"## {family}",
                "",
                "| id | title | bug class | priority | providers | requirements |",
                "|---|---|---|---|---|---|",
            ]
        )
        for scenario in scenarios:
            cells = [
                f"`{scenario.id}`",
                scenario.title,
                scenario.bug_class,
                scenario.priority,
                "<br>".join(
                    f"{provider} `{tiers.get(f'{provider}/{scenario.id}', 'no fixture')}`"
                    for provider in sorted(scenario.providers)
                ),
                "<br>".join(
                    f"{requirement.level} `{requirement.id}` ({requirement.check})"
                    for requirement in scenario.requirements
                ),
            ]
            lines.append("| " + " | ".join(_cell(cell) for cell in cells) + " |")
    return "\n".join(lines) + "\n"
