def test_catalog_writes_default_output(
    root: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    monkeypatch.chdir(root)
    assert main(["catalog"]) == 0
    assert (root / "docs" / "scenarios.md").read_bytes() == render(root).encode("utf-8")
    captured = capsys.readouterr()
    assert captured.out == "wrote docs/scenarios.md\n"
    assert captured.err == ""


@pytest.mark.parametrize("absolute", [False, True])
def test_catalog_output_paths(root: Path, absolute: bool) -> None:
    destination = root / "elsewhere" / "catalog.md"
    output = str(destination) if absolute else "elsewhere/catalog.md"
    command = ["catalog", "--root", str(root), "--out", output]
    assert main(command) == 0
    assert destination.read_bytes() == render(root).encode("utf-8")
    assert main([*command, "--check"]) == 0
    assert not (root / "docs").exists()


def test_catalog_stdout(root: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["catalog", "--root", str(root), "--out", "-"]) == 0
    captured = capsys.readouterr()
    assert captured.out == render(root)
    assert captured.err == ""
    assert not (root / "docs").exists()


@pytest.mark.parametrize("state", ["fresh", "stale", "missing", "crlf", "non-utf8"])
def test_catalog_check(root: Path, state: str, capsys: pytest.CaptureFixture[str]) -> None:
    destination = root / "docs" / "scenarios.md"
    text = render(root).encode("utf-8")
    content = {
        "fresh": text,
        "stale": text + b"\n",
        "missing": None,
        "crlf": text.replace(b"\n", b"\r\n"),
        "non-utf8": b"\xff",
    }[state]
    if content is not None:
        destination.parent.mkdir()
        destination.write_bytes(content)
    assert main(["catalog", "--root", str(root), "--check"]) == (0 if state == "fresh" else 1)
    captured = capsys.readouterr()
    assert captured.out == ""
    assert captured.err == (
        "" if state == "fresh" else "docs/scenarios.md is stale: run `wiretruth catalog`\n"
    )
    if content is None:
        assert not destination.parent.exists()
    else:
        assert destination.read_bytes() == content


