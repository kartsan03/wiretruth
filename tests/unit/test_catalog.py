import json
import shutil
from pathlib import Path

import pytest

from wiretruth.catalog import render
from wiretruth.cli import main
from wiretruth.formats import load_document, load_scenario

REPO = Path(__file__).resolve().parents[2]
VALID = REPO / "tests" / "samples" / "valid"


@pytest.fixture
def root(tmp_path: Path) -> Path:
    shutil.copytree(REPO / "suite", tmp_path / "suite")
    return tmp_path


def _write(path: Path, document: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document), encoding="utf-8")


def test_render_is_deterministic(root: Path) -> None:
    text = render(REPO)
    assert render(REPO) == text
    assert render(root) == text
    assert text.startswith("<!-- Generated by `wiretruth catalog`. Do not edit by hand. -->\n")
    assert text.endswith("\n") and not text.endswith("\n\n")
    assert str(REPO) not in text and str(root) not in text


def test_committed_catalog_is_fresh() -> None:
    assert (REPO / "docs" / "scenarios.md").read_bytes() == render(REPO).encode("utf-8")


def test_summary_and_fixture_tiers_come_from_data(tmp_path: Path) -> None:
    scenario = load_document("scenario", VALID / "scenario" / "structured-output.json")
    assert isinstance(scenario, dict)
    scenario.update(
        id="errors.example", providers=["openai-chat", "anthropic", "gemini-interactions"]
    )
    _write(tmp_path / "suite" / "scenarios" / "errors" / "example.json", scenario)
    for provider, sample in [
        ("openai-chat", "recorded-sse.json"),
        ("anthropic", "documented-json.json"),
        ("gemini-interactions", "derived-chunks-abort.json"),
    ]:
        fixture = load_document("fixture", VALID / "fixture" / sample)
        assert isinstance(fixture, dict)
        fixture.update(
            id=f"{provider}/errors.example", scenario="errors.example", provider=provider
        )
        if isinstance(fixture["derived_from"], dict):
            fixture["derived_from"]["fixture"] = "openai-chat/errors.example"
        _write(tmp_path / "suite" / "fixtures" / provider / "errors.example.json", fixture)
    text = render(tmp_path)
    assert "1 scenarios; 3 providers; fixtures: 1 recorded, 1 documented, 1 derived." in text
    assert (
        "anthropic `documented`<br>gemini-interactions `derived`<br>openai-chat `recorded`" in text
    )
    assert (
        "MUST `no-partial-success` (no_success_structured_value)"
        "<br>MUST `cause-is-truncation` (truncation_is_signalled)"
    ) in text
    assert "<br>SHOULD `usage-reported` (usage_matches_truth)" in text


def test_family_sections_and_scenarios_are_sorted(root: Path) -> None:
    directory = root / "suite" / "scenarios"
    (directory / "errors").mkdir()
    (directory / "notes.txt").write_text("Not a family.", encoding="utf-8")
    sections = render(root).split("\n## ")[1:]
    assert [section.splitlines()[0] for section in sections] == sorted(
        folder.name for folder in directory.iterdir() if folder.is_dir()
    )
    for section in sections:
        family = section.splitlines()[0]
        ids = [line.split("`")[1] for line in section.splitlines() if line.startswith("| `")]
        assert ids == sorted(load_scenario(path).id for path in (directory / family).glob("*.json"))
        assert (
            section.count("| id | title | bug class | priority | providers | requirements |") == 1
        )


@pytest.mark.parametrize("newline", ["\n", "\r\n", "\r"])
def test_cell_escaping(root: Path, newline: str) -> None:
    path = root / "suite" / "scenarios" / "truncation" / "text.json"
    scenario = load_document("scenario", path)
    assert isinstance(scenario, dict)
    scenario["title"] = f"First | second{newline}Third"
    _write(path, scenario)
    assert r"| First \| second<br>Third |" in render(root)


def test_missing_fixture_and_dated_variant(root: Path) -> None:
    path = root / "suite" / "fixtures" / "openai-chat" / "truncation.text.json"
    variant = load_document("fixture", VALID / "fixture" / "derived-chunks-abort.json")
    assert isinstance(variant, dict)
    variant.update(id="openai-chat/truncation.text@2026-10-01", scenario="truncation.text")
    _write(path.with_name("truncation.text@2026-10-01.json"), variant)
    row = next(line for line in render(root).splitlines() if line.startswith("| `truncation.text`"))
    assert "openai-chat `recorded`" in row
    path.unlink()
    row = next(line for line in render(root).splitlines() if line.startswith("| `truncation.text`"))
    assert "openai-chat `no fixture`" in row


